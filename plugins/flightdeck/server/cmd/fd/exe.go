package main

import (
	"os"
	"path/filepath"
	"strings"
)

// deletedSuffix 는 리눅스가 `/proc/<pid>/exe` 에 붙이는 표식이다.
//
// 프로세스가 연 파일이 그 뒤 교체·삭제되면 커널이 심볼릭 링크를 이렇게 낸다.
//
// ★ **그런데 os.Executable 로는 이 표식이 안 올라온다 — stdlib 이 먼저 뗀다.** 예전 이 자리에는
// "`os.Executable` 이 그 링크를 읽으므로 이 표식이 그대로 올라온다"고 적혀 있었다. **거짓이다.**
// 리눅스판은 링크를 읽은 그 자리에서 잘라 준다(os/executable_procfs.go:27 —
// `return stringslite.TrimSuffix(path, " (deleted)"), err`). darwin 은 _NSGetExecutablePath 라
// 표식이 애초에 없다. 2026-08-07 실측(go1.26.5, 프로브를 직접 돌려 재현했다) — 한 프로세스
// 안에서 두 값이 갈린다:
//
//	갈래                   os.Executable()   os.Readlink("/proc/self/exe")
//	자기 파일을 unlink     …/p1              …/p1 (deleted)
//	자기 자리가 rename     …/p2              …/p2 (deleted)   ← 런처(bin/fd)의 `mv -f` 경로
//
// 그래서 아래 CutSuffix 와 '교체됐다' 갈래는 **방어로만 산다.** 실물 호출부 둘(cmds.go 의
// doctor · bincache.go 의 pruneBinCache)이 **둘 다 os.Executable** 이고 `/proc/self/exe` 를
// readlink 하는 자리는 저장소에 없으므로, 지금 이 갈래는 한 번도 안 걸린다.
//
// ★ **그래도 지우지 않는다** — 지울지 남길지를 이번에 실제로 쟀다. ⑴ CutSuffix 는 안 걸리면
// 항등이라 값이 0 이다. ⑵ ExeLines 는 exe 를 **인자로** 받는 순수 함수다. 표식을 정말로 쓰려면
// 호출부가 리눅스에서 readlink 를 먼저 하면 되고, 그때 이쪽 순수 절반은 이미 옳고 시험도 서 있다.
// ⑶ 이 상수의 소비자가 bincache.go 에 하나 더 있어, 지우는 판단은 여기 혼자 못 내린다.
//
// ★ **그 readlink 를 지금 안 다는 것도 판정이다.** ⑴ doctor·훅은 수 ms 사는 프로세스라 그 창에서
// 자기 파일이 교체될 일이 사실상 없다 — 교체는 exec 앞뒤에 일어나고, exec 앞의 교체는 애초에
// 표식이 아니다. ⑵ 이 축이 진짜 값을 갖는 유일한 자리인 **오래 도는 서버**는 selfwatch 가
// 문자열이 아니라 **inode** 로 이미 덮는다(selfwatch.go 의 `w.stat("/proc/self/exe")` — 지금 도는
// 이미지의 inode 를 기준값으로 잡아 경로 stat 과 견준다. 표기에도 표식에도 안 흔들리는 옳은 쪽이다).
// 여기에 리눅스 전용 갈래를 새로 파면 같은 판정이 **세 번째 자리**에 살게 된다.
const deletedSuffix = " (deleted)"

// ExeLines 는 지금 도는 실행 파일에 대해 doctor 가 찍을 줄들이다.
//
// **거의 순수하다** — 파일시스템을 두드리는 자리는 아래 sameDirAs 하나뿐이고, 그 함수는
// 두 경로 문자열이 **이미 갈렸을 때만** stat 으로 내려간다(계약 전문은 그쪽 주석).
//
// ★ **파일이 아니라 프로세스를 찍는다.** 2026-08-05 실측: 설치 자리의 파일은 8분 전
// 최신으로 교체돼 있었는데(`vcs.revision` = 그 시각의 main tip) 그 자리를 도는 프로세스는
// 14시간 전 코드였다 — `/proc/<pid>/exe -> …/fd (deleted)`. 파일을 재는 진단은 그 상황에서
// "최신"이라 답하고, 응답하는 코드는 옛 것이다.
//
// 그래서 이 줄이 없으면 "판을 올렸는데 왜 그대로냐"에 답할 자리가 없다. 답은 **재기동**이고,
// 그 사실이 여기 없으면 사람은 빌드를 다시 하러 간다(그래 봐야 파일만 또 바뀐다).
//
// ★ **다만 그 관측은 전부 밖에서 한 것이다 — 프로세스 자신은 그 표식을 못 본다.** 위 `(deleted)`
// 는 셸이 남의 `/proc/<pid>/exe` 를 읽어 본 값이고, doctor 가 부르는 os.Executable 은 그것을
// 떼고 준다(아래 deletedSuffix ★, 2026-08-07 실측). 그래서 "판을 올렸는데 왜 그대로냐"에
// 이 함수가 실제로 답하는 통로는 아래 **둘째 축(자리)** 이고, 오래 도는 서버 쪽은 selfwatch 의
// inode 축이다. 첫째 축은 그 통로가 생길 때를 대비한 순수 절반으로만 서 있다.
//
// ★ **둘째 축 — 자리.** 위 축은 "이 **자리**의 파일이 바뀌었나"만 본다. 그 아래에 안 덮은
// 축이 하나 더 있었다: **이 자리가 아직 그 자리인가.** 2026-08-06 실측 — 바이너리 캐시가
// 채널 환경(CLAUDE_PLUGIN_DATA·XDG_STATE_HOME)을 타서 같은 소스가 두 자리에 두 번 지어졌고
// 두 자리의 빌드 시각이 55분 어긋났다(16:10:44 ↔ 17:05:29). 그 창에서 한 응답의 서버 축과
// 렌더 축이 서로 다른 판을 봤다. 그래서 자리를 채널 무관한 고정 자리로 옮겼다(판정 전문은
// 런처 bin/fd 의 자리 블록에 있다).
//
// 그런데 **옛 자리에서 이미 exec 된 프로세스는 그대로 돈다** — rename 은 디렉토리 엔트리만
// 바꾸고 도는 프로세스는 옛 inode 를 끝까지 문다(실측: 셋이 `(deleted)` 위에서 돌고
// 최고령이 2.28일이다). 이행 창은 며칠이고, 그 창에서 이 줄이 없으면 **옛 자리를 도는
// 프로세스가 스스로 그것을 못 말한다.** 위 축은 거기서 **언제나** 침묵한다 — 옛 런처를 가진
// 세션이 옛 자리를 계속 갱신해 주면 커널이 표식조차 안 붙이고, 붙이더라도 os.Executable 이
// 떼고 준다(위 deletedSuffix ★). 즉 첫째 축은 실물에서 안 뜬다. "지금 계산되는 자리"와 견주는
// 이 둘째 축이 **doctor 가 실제로 무언가를 말하는 유일한 자리**다.
//
// 두 축은 **동시에 참일 수 있고, 그래서 둘 다 낸다.** 옛 자리에서 도는 프로세스가 실제로
// 그 모양이다 — 옛 런처가 그 자리를 다시 지으면 표식이 붙고, 자리는 여전히 밖이다
// (첫째가 실물에서 안 뜨는 것은 **입력원**이 표식을 떼기 때문이지 둘째가 그것을 덮어서가
// 아니다 — 그래서 둘로 남긴다).
// 사람이 할 일도 다르다: 첫째는 "재기동하면 **이 자리의** 새 파일", 둘째는 "재기동하면
// **다른 자리의** 것"(단 둘째의 처방은 **런처로 뜬 프로세스일 때만** 선다 — 아래 ★).
// 둘 중 하나로 접으면 답의 절반이 사라진다.
//
// ★ **wantDir 가 비면 이 갈래를 안 낸다.** 자리를 계산할 수 없는 경우(HOME 도 FD_STATE_DIR
// 도 없어 애초에 지을 자리가 없다)에 "자리 밖이다"라고 답하면 **안 잰 축을 잰 척하는**
// 것이다(설계 §13). 모르면 침묵한다.
//
// ★ **파일 이름을 안 본다 — 부모 디렉토리만 견준다.** 이름에 소스 트리를 접어 넣는 키
// 규칙은 런처가 유일한 주인이다. 그 규칙의 사본을 여기 두면 한쪽만 고칠 때 조용히
// 어긋난다(client.go 의 newClient 주석이 적어 둔 규율 — 이 레포는 그 사고를 세 번 겪었다).
// 그래서 이름이 무엇이든 **부모가 지금 자리면 통과**다.
//
// ★ **심볼릭 링크 아래에서 거짓 경보를 안 낸다 — 자리 판정은 sameDirAs 하나가 답한다.**
// 예전 이 자리에는 "링크를 안 푼다 — 링크로 자리를 우회한 사람이 이 줄을 보는 건 거짓
// 경보가 아니다, 정말로 자리가 둘이다"라고 적혀 있었다. **그 사실 주장이 틀렸다.**
// 2026-08-07 실측 재현: 가짜 홈의 `~/.cache` 를 다른 디스크로 링크해 두고 런처로 doctor 를
// 돌리면 **방금 지어 exec 한 바로 그 파일**에 "자리 밖"이 붙고, 재기동해도 안 사라진다.
// 자리를 우회한 것이 아니라 **한 자리를 두 이름으로 부른** 것이다. 지울 수 없는 거짓 경보가
// 붙으면 다음에 **진짜** 갈림이 났을 때 아무도 이 줄을 안 믿는다.
//
// 왜 문자열이 아니라 inode 인지 · 왜 EvalSymlinks 가 아닌지 · 어떤 홈이 그 모양인지는
// **sameDirAs·sameDir 주석에 한 벌만 있다.** 여기 다시 적지 않는다 — 같은 갈림이
// selfwatch.go 에도 있고, 그 사본이 두 벌이던 것이 이 함수를 고친 후속의 사유였다.
//
// ★ **"런처 산출물이다"를 전제하지 않는다 — 사실만 단정하고 처방에 조건을 단다.** 전제가
// 거짓인 배치가 둘 있다. ⑴ 컨테이너 이미지(`/usr/local/bin/fd`. Dockerfile 의 HEALTHCHECK 가
// 30초마다 바로 `fd doctor` 이고 그 stdout 이 `State.Health.Log` 에 쌓인다. 실측 그 안의
// HOME 은 `/` 라 wantDir 이 `/.cache/flightdeck/bin` 으로 **계산은 되고**, 그 자리는 거기서
// 영영 안 생긴다 — 즉 wantDir=="" 가드가 안 걸린다) ⑵ 개발용 `go run`(exe 가 go-build
// 캐시의 일회용 파일이다. README 가 안내하는 경로다). 둘 다 재기동해도 영원히 같은 자리라
// 예전 문장의 "아무도 갱신하지 않는 옛 자리다 · 옮겨졌다 · 재기동하면 새 자리 것으로
// 뜬다"가 **셋 다 거짓**이었다. 그래서 두 배치 모두에 참인 **사실**(런처가 짓는 자리 밖이다
// = 런처는 이 파일을 갱신하지 않는다)만 단정하고 **처방**(재기동)은 "런처로 뜬 프로세스라면"
// 이라는 조건 아래 둔다. selfwatch 의 containerVerdict 가 같은 축에 내린 판정과 방향이
// 같다 — 모르는 것을 아는 척하지 않는다(설계 §13).
//
// ★ **이름(`fd-` 접두)으로 좁혀 푸는 쪽은 안 된다.** 옛 런처가 짓던 이름은 접두 없는 `fd`
// 다(개정 전 bin/fd 의 `bin="$state/bin/fd"`). 접두를 **포함** 조건으로 쓰면 이 축이
// 존재하는 유일한 이유인 이행 창이 통째로 침묵한다(실제로 얹어 보면 아래 시험의 "옛 자리를
// 돌면 말한다"가 깨진다). bincache.go 의 접두는 '지울 것'을 좁히는 **배제** 조건이라
// 방향이 반대다.
//
// ★ **"옛 사다리 자리 목록"과 견주는 쪽(긍정 검사)도 안 쓴다.** 컨테이너에서 아예 침묵하니
// 더 깔끔해 보이지만 ⑴ 자리 판단의 사본이 BinCacheDir 밖에 하나 더 생기고(이 레포가 세 번
// 겪은 사고다) ⑵ 그 목록은 얼어붙은 과거라, 목록에 없는 옛 자리를 도는 프로세스는 **아무
// 말도 못 듣는다** — 거짓 경보를 지우려다 이 축의 존재 이유를 잃는다. 문장을 사실과 처방으로
// 가르면 두 배치 모두에 참인 한 줄로 끝나고, 새로 살 판단이 없다.
//
// os.Executable 을 안에서 부르지 않고 그 반환을 **인자로 받는다** — 시험이 갈래를 다 줄 수
// 있어야 한다. 교체 갈래는 시험이 문자열로만 만들 수 있다(실제 프로세스로도 못 만든다 —
// 프로세스는 정말로 교체돼도 os.Executable 이 표식을 떼고 주기 때문이다. 위 deletedSuffix ★).
// wantDir 도 같은 이유로 인자다: 자리 계산은 BinCacheDir 하나가 갖고, 여기는 견주기만 한다.
func ExeLines(exe string, err error, wantDir string) []string {
	if err != nil {
		return []string{"! 실행 파일 자리를 못 읽었다: " + clip(err.Error(), 200)}
	}
	path, replaced := strings.CutSuffix(exe, deletedSuffix)
	lines := []string{"실행 파일 " + path}
	if replaced {
		lines = append(lines,
			"! 그 자리의 파일은 **교체됐다** — 이 프로세스는 옛 코드를 계속 돈다. "+
				"새 판으로 돌리려면 재기동해야 한다(빌드를 다시 해도 안 바뀐다).")
	}
	if want := strings.TrimSpace(wantDir); want != "" {
		// ★ 이 Clean 은 **사람에게 보여 줄 자리**를 위한 것이다 — 아래 문구에 그대로 박히고
		// 시험이 그 문자열을 단정한다. 견주기 쪽 Clean 은 sameDirAs 가 제 몫으로 또 한다
		// (멱등이라 값이 0 이다). 여기서 안 하면 화면에 끝 슬래시·`//` 가 그대로 나간다.
		want = filepath.Clean(want)
		if !sameDirAs(filepath.Dir(path), want) {
			lines = append(lines,
				"! 이 실행 파일은 **런처가 짓는 자리 밖**이다("+want+"). 런처(bin/fd)로 뜬 "+
					"프로세스라면 **옛 자리**를 도는 것이라 재기동하면 새 자리 것으로 뜬다. "+
					"컨테이너 이미지(/usr/local/bin/fd)나 go run·손빌드면 자리는 원래 거기다 — "+
					"그때 이 줄이 말하는 것은 **런처가 이 파일을 갱신하지 않는다**는 사실뿐이고, "+
					"갱신은 그 배치의 방식(이미지 다시 굽기·다시 빌드)으로 한다.")
		}
	}
	return lines
}

// sameDirAs 는 두 경로가 **같은 자리인가**다. 이 패키지에서 자리를 견주는 **유일한 자리**다.
//
// ★ **비교 자체가 아니라 그것을 감싸는 세 조각을 모으려고 있는 함수다.** 판정(os.SameFile)은
// 앞선 라운드가 이미 sameDir 한 자리로 모았는데, **감싸는 셋** — ⑴ 양쪽 Clean ⑵ 문자열
// 지름길 ⑶ 그다음에야 sameDir — 은 여전히 두 곳에 각각 살아 있었다: ExeLines(부정 방향
// "자리 밖인가")와 newSelfWatcher(긍정 방향 "런처 자리인가"). 한쪽에서 Clean 을 빼는 편집이
// 오면 두 화면이 다시 갈리는데, **그 갈림은 심볼릭 링크 홈에서만 드러난다** — 링크가 없는
// 머신에서는 갈린 채로도 전 시험이 초록이라 아무도 못 본다. 같은 질문의 답은 한 자리에서만
// 산다(client.go 의 newClient 규율 — 이 레포는 그 사고를 세 번 겪었다).
//
// ★ **문자열 지름길이 stat 앞에 있는 것이 계약이다** — sameDir 이 여기 오기 전 갖고 있던
// 그 계약을 옮겨 적는다. 자리가 맞는 프로세스, 즉 **정상은 stat 을 한 번도 안 친다**
// (doctor·훅은 수 ms 사는 프로세스다).
//
// 순서를 뒤집으면 비용만 느는 것이 아니라 **답이 바뀌는 갈래**가 하나 있다: 그 디렉토리가
// 통째로 없어진 뒤다. 문자열은 정확히 같은데 stat 은 양쪽 다 실패하고, sameDir 은 실패를
// false 로 접으므로(그쪽 ★) **제자리에 있는 프로세스가 "자리 밖"이라는 답을 받는다.**
// 사람이 `~/.cache/flightdeck` 를 지운 뒤 · FD_STATE_DIR 가 지워지는 임시 자리를 가리키는
// 구성이 그 모양이다. 좁은 갈래이지만 방향이 나쁘다 — 거짓 경보 쪽이다.
// 그 갈래를 exe_test.go 의 표가 잰다(없는 자리끼리도 문자열이 같으면 같다).
func sameDirAs(a, b string) bool {
	a, b = filepath.Clean(a), filepath.Clean(b)
	return a == b || sameDir(a, b)
}

// sameDir 는 두 경로가 **같은 디렉토리를 두 이름으로 부른 것인가**다.
//
// ★ **호출부는 sameDirAs 하나여야 한다.** Clean 과 문자열 지름길은 그쪽 계약이라 여기 없다 —
// 이 함수가 답하는 것은 "문자열이 갈렸는데도 같은 자리인가" 하나다. 직접 부르면 감싸는
// 세 조각이 다시 두 벌이 된다(그 규율을 exe_test.go 의 호출부 시험이 파서로 잠근다).
//
// 문자열이 아니라 **inode** 로 견준다. 리눅스의 os.Executable 은 `/proc/self/exe` 라 **완전히
// 푼 경로**를 주고, 견주는 상대(doctor 의 wantDir · 감시기의 binDir)는 HOME 을 그대로 이어
// 붙인 **안 푼 경로**라, 문자열로만 견주면 링크가 하나라도 끼는 순간 **항상** 어긋난다.
// 그런 홈은 흔하다 — `~/.cache` 를 큰 디스크로 옮긴 구성 · `/home -> /var/home` 이 기본인
// 배포판 · NFS 홈. 그 머신들에서 두 소비부는 영영 거짓말을 한다(각자의 실측은 각자 주석에).
//
// ★ **EvalSymlinks 를 한쪽에만 거는 쪽으로 풀지 마라** — darwin 의 os.Executable 은 execve 에
// 넘어간 **안 푼 경로**를 주므로(`/tmp` → `/private/tmp`) 방향이 뒤집혀 같은 거짓 경보가
// 거기서 난다. os.SameFile 은 양쪽 표기를 안 보므로 두 판에서 같이 옳다.
//
// ★ **stat 이 실패하면 판정을 안 접는다(false).** 옛 자리가 통째로 지워진 이행 창이 그
// 모양이고, 그때는 자리가 정말로 밖이다. 모르면 부른 쪽의 문자열 판정을 그대로 둔다 —
// 여기가 답을 뒤집는 것은 **같은 자리임을 실제로 확인했을 때뿐**이다.
func sameDir(a, b string) bool {
	fa, err := os.Stat(a)
	if err != nil {
		return false
	}
	fb, err := os.Stat(b)
	if err != nil {
		return false
	}
	return os.SameFile(fa, fb)
}
