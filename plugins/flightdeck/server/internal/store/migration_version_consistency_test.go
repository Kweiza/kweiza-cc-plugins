package store

import "testing"

// 스키마 판을 말하는 자리가 **둘**이다 — 그 둘이 같은 것을 말하는지 문다.
//
//	· `SchemaVersion` (상수)     — 목표 판. `MigrateTo(ctx, path, SchemaVersion, log)` 가 이것을 쓴다
//	· `migrations` (슬라이스)     — 실제로 얹을 증분들
//
// ★★ 2026-08-23 실기동 검증 중 **우연히** 드러났다. 실패 갈래를 태우려고 슬라이스에
// `{To: 13, SQL: "(문법 오류)"}` 를 더하고 컨테이너를 띄웠는데, 기대한 exit 1 대신
// **`이미 맞다 — 스키마 12판`** 을 내고 정상 종료했다. 목표 판은 슬라이스가 아니라 상수가
// 정하므로, **증분만 더하면 그것은 목록에 앉아 있을 뿐 영영 안 돈다.**
//
// ★ 나타나는 모양이 오류가 아니라 **부재**다:
//
//	· `fd migrate` 가 **성공으로 끝난다**(exit 0). compose 의
//	  `service_completed_successfully` 가 통과하고 서버가 정상으로 뜬다
//	· 화면에는 `이미 맞다` 라고 적힌다 — 맞지 않은데
//	· 그 증분이 만들려던 컬럼·인덱스가 없으므로 그것을 쓰는 코드가 **런타임에** 죽고,
//	  그때는 원인이 마이그레이션이라는 것이 안 드러난다
//	· 릴리스에 실려 나가면 **모든 머신이 같은 상태**가 된다
//
// ★★ **왜 옆 축으로는 못 잡나 — 실측했다.** 상수를 안 올린 채 증분 하나를 더하고
// `go test ./internal/...` 를 돌린 결과다(2026-08-23):
//
//	그 증분이 하는 일        | 전 패키지 결과
//	------------------------|------------------------------------------------
//	CREATE TABLE            | 🔴 — 단 `TestDeclaredTablesMatchDesign` 등 **표 목록 축**이다
//	ALTER TABLE ADD COLUMN  | 🟢 **아무도 안 물었다**
//	CREATE INDEX            | 🟢 **아무도 안 물었다**
//	UPDATE                  | 🔴 — `TestBundledMigrationsAreAdditive` 등 **파괴적 조작 축**이다
//
// 빨간 둘은 **드리프트를 잡은 것이 아니다.** 그 축들은 "증분 SQL 텍스트에 새 표/파괴적
// 조작이 나타났는가"를 보므로, 상수를 제대로 올려 증분이 **정상으로 돌 때도 똑같이** 빨개진다.
// 즉 드리프트에 대해서는 아무 정보가 없다. 그리고 컬럼·인덱스는 증분의 가장 흔한 모양인데
// 거기에는 잡는 것이 하나도 없었다.
//
// ★ 반대 방향(상수만 올리고 증분을 안 더함)은 이미 잘 막힌다 — 실측에서 723건이 빨개진다.
// 그래서 이 시험이 사는 이유는 **한 방향**이다. 그래도 양쪽을 같은 단정으로 무는 이유는,
// 723건이 빨개지는 화면은 **원인을 안 말해 주기 때문**이다. 여기 한 줄이 이름을 댄다.
func TestSchemaVersionMatchesTheMigrationList(t *testing.T) {
	// ★ 빈 목록을 통과로 접지 않는다. 슬라이스가 비면 아래 순회가 한 번도 안 돌고
	// 마지막 항목도 없어서, 이 시험은 **아무것도 안 보면서 초록**이 된다.
	if len(migrations) == 0 {
		t.Fatal("전제가 깨졌다 — 증분 목록이 0건이다. 볼 것이 없으면 지킬 것도 없다")
	}

	// 사다리에 빈칸이 없어야 한다. `applyUpgrades` 는 현재 판 다음 것부터 순서대로 얹는데,
	// 번호가 뛰면 그 위는 영영 안 얹히고 아래는 두 번 얹힐 수 있다.
	want := BaseSchemaVersion + 1
	for i, m := range migrations {
		if m.To != want {
			t.Fatalf("증분 목록의 %d번째가 To=%d 다 — %d 를 기대했다(%q).\n"+
				"판 번호는 BaseSchemaVersion(%d) 바로 위부터 **빈칸 없이 하나씩** 올라야 한다.\n"+
				"뛰면 그 위 증분이 영영 안 얹히고, 되돌아가면 아래가 두 번 얹힌다 —\n"+
				"둘 다 적용은 성공으로 끝나므로 화면에는 아무 오류도 안 뜬다",
				i, m.To, want, m.Name, BaseSchemaVersion)
		}
		want++
	}

	last := migrations[len(migrations)-1].To
	if last != SchemaVersion {
		t.Fatalf("SchemaVersion 은 %d 인데 마지막 증분은 To=%d(%q) 다.\n"+
			"목표 판을 정하는 것은 **상수**이므로(MigrateTo(…, SchemaVersion, …)),\n"+
			"  · 상수 < 목록 : 그 위 증분들이 **영영 안 돈다**. `fd migrate` 는 exit 0 으로 끝나고\n"+
			"                  화면에 `이미 맞다` 라고 적는다. 그 증분이 만들려던 컬럼·인덱스가\n"+
			"                  없으므로 그것을 쓰는 코드가 런타임에 죽는데, 그때는 원인이\n"+
			"                  마이그레이션이라는 것이 안 드러난다\n"+
			"  · 상수 > 목록 : 판을 채울 증분이 없다\n"+
			"증분을 더했으면 **상수도 같이 올려라.** 둘은 한 사실의 두 표기다",
			SchemaVersion, last, migrations[len(migrations)-1].Name)
	}
}
